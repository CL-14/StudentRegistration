    //Reworked the search student function as well
    // Search the database by student ID.
    fun searchStudent(
        id: Int,
        onResult: (Student?) -> Unit
    ) {
        viewModelScope.launch(Dispatchers.IO) {

            val student = studentDao.searchStudent(id)


            withContext(Dispatchers.Main) {
                onResult(student)
            }
        }
    }
}






