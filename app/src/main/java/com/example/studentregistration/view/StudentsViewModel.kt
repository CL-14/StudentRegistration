package com.example.studentregistration.view

import androidx.lifecycle.LiveData
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import com.example.studentregistration.Student
import com.example.studentregistration.MainApplication
import kotlinx.coroutines.withContext
//deleted unused imports


class StudentsViewModel : ViewModel() {

    // Get access to the DAO through our database instance.
    private val studentDao by lazy {
        MainApplication.studentDatabase.getStudentDao()
    }

    //reworked the entire add student function:

    // Save a student using the information supplied by the form.
    fun addStudent(
        name: String,
        course: String,
        year: Int,
        onResult: (Boolean) -> Unit
    ) {
        viewModelScope.launch(Dispatchers.IO) {

            // I don't need to add the id since it will be generated by room in this case
            studentDao.addStudent(
                Student(
                    StudentName = name,
                    Course = course,
                    Year = year
                )
            )

            withContext(Dispatchers.Main) {
                onResult(true)
            }
        }
    }

